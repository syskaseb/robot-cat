"""Recover saved native W060 construction after a deleted-proxy check error.

R1 CAD is retained; new copies get independent parameter/reopen checks.
Own native documents only. Do not recompute the interactive assembly.
"""
from datetime import datetime,timezone
import json,math,shutil,sys,tempfile
from pathlib import Path
import main_input_return_r4 as R4
R=R4.M
import body_ground_routes_r1 as M
ROOT=M.ROOT
PRIOR=ROOT/'hardware/electronics/full-cat/main-input-return-finish-r1'
PRIOR_CAD=ROOT/'hardware/cad/studies/main-input-return-finish-r1'
OUT=ROOT/'hardware/electronics/full-cat/main-input-return-finish-r2'
CAD=ROOT/'hardware/cad/studies/main-input-return-finish-r2'

def main():
    import FreeCAD as A
    import Part,MeshPart
    OUT.mkdir(parents=True,exist_ok=True);CAD.mkdir(parents=True,exist_ok=True)
    assert not (OUT/'checks.json').exists()
    start=datetime.now(timezone.utc);sources={};native={};seats={};exports={}
    def box(b):return Part.makeBox(b[3]-b[0],b[4]-b[1],b[5]-b[2],A.Vector(*b[:3]))
    configs=[('Deck','DeckMainInput.FCStd','MainInputDeck','MainInputParameters','PortalHeight',8,('G1InputSeat','InputPortalSeat')),
             ('MAIN','MainInputMount.FCStd','MainInputAdapter','InputSeatParameters','PostHeight',20,('InputMainSeat',))]
    for key,filename,final_name,parameter,prop,value,seat_names in configs:
        source=PRIOR_CAD/filename;sources[source.relative_to(ROOT).as_posix()]=M.sha(source)
        d=A.openDocument(str(source));docname=d.Name;dest=CAD/filename
        try:
            d.saveAs(str(dest));d.recompute();o=d.getObject(final_name);p=d.getObject(parameter)
            sk=[s for s in d.Objects if s.TypeId=='Sketcher::SketchObject']
            # Count new constrained interfaces, not historical imported sketches.
            added=[s for s in sk if s.Name in ('MainInputPassages','G1InputFoot','InputPortalFoot','InputSeatRoot','InputSeatBeamFoot')]
            assert len(added)==(3 if key=='Deck' else 2)
            assert all(s.FullyConstrained and s.solve()==0 for s in added)
            shape=o.Shape.copy();assert shape.isValid() and len(shape.Solids)==1 and not shape.check(True)
            volume=shape.Volume;setattr(p,prop,value+.1);d.recompute();probe=o.Shape.Volume
            assert abs(probe-volume)>1e-6
            setattr(p,prop,value);d.recompute();assert abs(o.Shape.Volume-volume)<1e-5
            for n in seat_names:
                s=d.getObject(n).Shape.copy()
                if key=='MAIN':s.translate(A.Vector(105.82,8.16,52))
                seats[n]=s
            if key=='Deck':
                removed=d.GroundSupportedDeck.Shape.cut(d.MainInputSlottedDeck.Shape).Volume
                assert abs(removed-(12.8+math.pi*2.5**2)*4)<1e-4
                assert Part.makeCylinder(1.51,20,A.Vector(132.5,0,104.9)).common(shape).Volume<1e-5
            else:
                assert d.InputCurveGrooveTool.Shape.isValid()
                # Exact curve is frozen, traceable construction geometry; foot,
                # post and beam dimensions remain editable native features.
                gt=d.InputCurveGrooveTool
                gt.addProperty('App::PropertyString','SourceCentreline');gt.SourceCentreline='main-input-return-r4/W060_9_CENTERLINE.brep; generated by R4.geometry()'
                gt.addProperty('App::PropertyString','RouteChecksSHA256');gt.RouteChecksSHA256=M.sha(R.OUT/'checks.json')
            d.save();exports[key]=shape
            native[key]=dict(parameter_probe_mm3=[volume,probe,volume],added_constrained_sketches=len(added),strict_BOP_errors=0)
        finally:A.closeDocument(docname)
        with tempfile.TemporaryDirectory(prefix='robot-cat-main-in-reopen-') as td:
            q=Path(td)/filename;shutil.copy2(dest,q);d=A.openDocument(str(q));docname=d.Name
            try:
                d.recompute();s=d.getObject(final_name).Shape
                assert s.isValid() and len(s.Solids)==1 and not s.check(True)
                assert abs(s.Volume-volume)<1e-5
                native[key]['relocated_reopen']=True
            finally:A.closeDocument(docname)
    deck=exports['Deck'];mount=exports['MAIN'].copy();mount.translate(A.Vector(105.82,8.16,52))
    bands={}
    bb=[box([x-.6,11.75,103.8,x+.6,14.25,116.4]) for x in (75.5,86.5)]
    bb += [box([74.9,11.75,115.2,87.1,14.25,116.4]),box([74.9,11.75,103.8,87.1,14.25,105]),box([85.5,10.5,100.1,91.5,15.5,104.1])]
    for i,s in enumerate(bb):bands[f'G1_input_tie_{i}']=s
    portal=[box([126.3,-4.2,111.8,127.5,4.2,114.3]),box([134,-4.2,111.8,135.2,4.2,114.3]),
            box([127.5,-4.2,111.8,134,-3,114.3]),box([127.5,3,111.8,134,4.2,114.3]),box([126.8,4.2,110.3,132.8,9.2,114.3])]
    for i,s in enumerate(portal):bands[f'Deck_input_tie_{i}']=s
    # Loose prototype tie reserve encloses the sloped wire's complete OD
    # across2.5mm width; do not force it into a flat horizontal band at89.9.
    main=[box([129.25,-2.1,81.8,131.75,-.9,94.4]),box([129.25,6,81.8,131.75,7.2,94.4]),
          box([129.25,-.9,81.8,131.75,6,83]),box([129.25,-.9,93.2,131.75,6,94.4]),box([127.5,7.2,92.2,133.5,12.2,96.2])]
    for i,s in enumerate(main):bands[f'MAIN_input_tie_{i}']=s
    wires={}
    for f in sorted(R.OUT.glob('W060_*_DESIGN.brep')):
        s=Part.Shape();s.read(str(f));wires[f.stem]=s
    edges=R.geometry();neck=edges[-1];curve=edges[-2]
    def tube(e,r):return Part.Wire([e]).makePipeShell([Part.Wire([Part.makeCircle(r,e.valueAt(e.FirstParameter),e.tangentAt(e.FirstParameter))])],True,False)
    inner=tube(neck,1.1);par=curve.getParameterByLength(curve.Length-6.01);tail=curve.Curve.toShape(par,curve.LastParameter)
    boot=Part.Wire([tail,neck]).makePipeShell([Part.Wire([Part.makeCircle(2.1,tail.valueAt(tail.FirstParameter),tail.tangentAt(tail.FirstParameter))])],True,False)
    assert tail.Length>=6
    sleeves={'W060_neck_inner':inner,'W060_input_outer_boot':boot}
    owners,hashes=R.current_owners();owners.pop('Deck_R38');owners.pop('MAIN/Adapter')
    rows=[]
    def check(n,s,m,t):
        for i,q in enumerate(s.Solids):
            for j,v in enumerate(t.Solids):
                if q.BoundBox.intersect(v.BoundBox):rows.append(dict(part=n,owner=m,solid=i,owner_solid=j,hit_mm3=q.common(v).Volume))
    for n,s in {**seats,**bands,**wires,**sleeves}.items():
        for m,t in owners.items():
            if n==f'W060_{len(edges)-1}_DESIGN' and m=='MAIN/SupplierFamilyReference':continue
            check(n,s,m,t)
    for n,s in {**wires,**sleeves,**bands}.items():
        check(n,s,'NewDeck',deck);check(n,s,'NewMAINMount',mount)
    for n,s in {**seats,**bands}.items():
        for m,t in {**wires,**sleeves}.items():check(n,s,m,t)
    hits=[r for r in rows if r['hit_mm3']>1e-5]
    for n,s in {**seats,**bands,**sleeves,'Deck':deck,'MAINMount':mount}.items():s.exportBrep(str(CAD/(n+'_WORLD.brep')))
    end=datetime.now(timezone.utc);c=json.loads((R.OUT/'checks.json').read_text(encoding='utf-8'))
    result=dict(status='REJECTED' if hits else 'W060_COMPLETE_NOMINAL',hits=hits,rows=rows,native_checks=native,
        replaced_print_jobs=2,new_print_jobs=0,route_length_mm=c['length_mm'],nominal_blank_mm=220,
        outer_boot_intact_overlap_mm=tail.Length,source_sha256={**hashes,**sources},source_script_sha256=M.sha(Path(__file__)),
        physical_pass=False,W5_complete=False,started_utc=start.isoformat(),finished_utc=end.isoformat(),worker_wall_seconds=(end-start).total_seconds())
    if not hits:
        dims={}
        for n,s in exports.items():
            mesh=MeshPart.meshFromShape(Shape=s,LinearDeflection=.08,AngularDeflection=.15,Relative=False)
            assert mesh.isSolid() and mesh.countComponents()==1
            b=mesh.BoundBox;mesh.translate(-b.XMin,-b.YMin,-b.ZMin)
            dims[n]=[mesh.BoundBox.XLength,mesh.BoundBox.YLength,mesh.BoundBox.ZLength];assert max(dims[n])+10<=256
            mesh.write(str(CAD/(n+'_x1.stl')))
        result['dimensions_mm']=dims
    M.save(OUT/'checks.json',result)
    interface=json.loads((PRIOR/'interface.json').read_text(encoding='utf-8'))
    interface.update(status=result['status'],restraints_complete=not hits,new_STL=2 if not hits else 0,
        insulation=dict(inner_SKU='TE5052942064 RNF-100-3/32-0-STK',inner_blank_mm=4,
                        outer_SKU='TE5053042067 RNF-100-3/16-0-STK',outer_blank_mm=15,
                        placed_intact_overlap_mm=tail.Length,finished_outer_OD_reserve_mm=4.2,
                        note='Existing shared stock; shrink off PETG. Actual shrink/diameter and dry fit in phase2.'),
        recovery='R1 source saved; deleted Sketch.Document proxy caused check failure, not a failed CAD geometry assertion.',
        native_sources={n:(CAD/f).relative_to(ROOT).as_posix() for n,f,*_ in configs})
    M.save(OUT/'interface.json',interface)
    preview=[]
    for n,s in {**seats,**bands,**wires,**sleeves,'Deck':deck,'MAINMount':mount}.items():
        vs,ts=s.tessellate(.4);preview.append(dict(name=n,vertices=[list(v) for v in vs],triangles=ts))
    M.save(OUT/'preview-geometry.json',preview)
    print(json.dumps(dict(status=result['status'],hits=hits,pairs=len(rows))),flush=True)

if __name__=='__main__':
    sys.path.insert(0,str(ROOT/'tools/cad'));main()
